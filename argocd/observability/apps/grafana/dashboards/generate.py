def _base(i, kind, title, x, y, w, h, desc, ds):
    return {"id": i, "type": kind, "title": title, "description": desc, "datasource": ds,
            "gridPos": {"x": x, "y": y, "w": w, "h": h}}


def stat(i, title, expr, x, y, w=4, h=4, unit="none", steps=None, desc="", ds=P):
    p = _base(i, "stat", title, x, y, w, h, desc, ds)
    p["targets"] = [{"refId": "A", "expr": expr, "instant": True}]
    p["options"] = {"reduceOptions": {"calcs": ["lastNotNull"]}, "colorMode": "background" if steps else "none",
                    "graphMode": "none", "textMode": "value"}
    p["fieldConfig"] = {"defaults": {"unit": unit, "noValue": "0", "thresholds": {"mode": "absolute",
                        "steps": steps or [{"color": "text", "value": None}]}}, "overrides": []}
    return p


def ts(i, title, targets, x, y, w=12, h=8, unit="none", desc="", bars=False, stack=False, ds=P):
    p = _base(i, "timeseries", title, x, y, w, h, desc, ds)
    p["targets"] = [{"refId": chr(65 + n), "expr": e, "legendFormat": lf} for n, (e, lf) in enumerate(targets)]
    p["options"] = {"legend": {"displayMode": "list", "placement": "bottom", "showLegend": True},
                    "tooltip": {"mode": "multi", "sort": "desc"}}
    p["fieldConfig"] = {"defaults": {"unit": unit, "color": {"mode": "palette-classic"},
                        "custom": {"lineWidth": 2, "fillOpacity": 60 if bars else 0, "showPoints": "never",
                                   "drawStyle": "bars" if bars else "line",
                                   "stacking": {"mode": "normal" if stack else "none"}}}, "overrides": []}
    return p


def table(i, title, expr, x, y, w=12, h=8, desc="", rename=None, unit=None, sort=None):
    p = _base(i, "table", title, x, y, w, h, desc, P)
    p["targets"] = [{"refId": "A", "expr": expr, "instant": True, "format": "table"}]
    p["transformations"] = [{"id": "organize", "options": {"excludeByName": {"Time": True}, "renameByName": rename or {}}}]
    p["fieldConfig"] = {"defaults": {"unit": unit} if unit else {}, "overrides": []}
    if sort:
        p["options"] = {"sortBy": [{"displayName": sort, "desc": False}]}
    return p


def logs(i, title, expr, x, y, w=24, h=12, desc=""):
    p = _base(i, "logs", title, x, y, w, h, desc, L)
    p["targets"] = [{"refId": "A", "expr": expr}]
    p["options"] = {"showTime": True, "wrapLogMessage": True, "sortOrder": "Descending", "enableLogDetails": True,
                    "dedupStrategy": "none", "prettifyLogMessage": False}
    return p


def var_query(name, query, label=None, ds=P, multi=False, include_all=False, regex=""):
    return {"name": name, "label": label or name, "type": "query", "datasource": ds, "refresh": 2,
            "query": {"query": query, "refId": name}, "definition": query, "multi": multi,
            "includeAll": include_all, "sort": 1, "regex": regex}


def var_text(name, label, default=""):
    return {"name": name, "label": label, "type": "textbox", "query": default, "current": {"value": default}}


